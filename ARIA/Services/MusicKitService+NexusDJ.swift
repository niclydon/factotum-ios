import Foundation
import MusicKit

/// Nexus DJ playlist materialization, split from MusicKitService.swift
/// in the Factotum 4.0 foundation pass.
extension MusicKitService {
    // MARK: - Nexus DJ Playlist Materialization

    /// Fetches the latest Nexus DJ recommendation and creates / updates an
    /// Apple Music playlist named "Nexus DJ" from it. The playlist contains
    /// the recommended tracks, in order. Tracks the server suggests that we
    /// can't match against the on-device library are silently skipped.
    ///
    /// Idempotent: server marks the recommendation as `ios_playlist_created`
    /// after a successful materialize, so subsequent calls within the same
    /// 2-hour window are no-ops.
    func syncNexusDjPlaylist() async {
        guard isAuthorized else { return }

        let rec: MusicRecommendation?
        do {
            rec = try await APIClient.shared.fetchMusicRecommendation()
        } catch {
            Logger.shared.logVerbose("musickit", "Nexus DJ fetch failed: \(error.localizedDescription)")
            return
        }
        guard let rec else { return }
        if rec.ios_playlist_created {
            Logger.shared.logVerbose("musickit", "Nexus DJ rec \(rec.id.prefix(8)) already materialized; skipping")
            return
        }

        Logger.shared.log("musickit", "Materializing Nexus DJ playlist (\(rec.tracks.count) tracks, steer=\(rec.steer_direction ?? "none"))")

        // Resolve each server-side track against the local MusicKit catalog.
        // We search by title + artist; if multiple hits, take the first.
        var resolved: [Song] = []
        for track in rec.tracks {
            do {
                var search = MusicCatalogSearchRequest(term: "\(track.title) \(track.artist_name)", types: [Song.self])
                search.limit = 5
                let response = try await search.response()
                if let hit = response.songs.first(where: { song in
                    song.title.lowercased() == track.title.lowercased()
                        && song.artistName.lowercased() == track.artist_name.lowercased()
                }) ?? response.songs.first {
                    resolved.append(hit)
                }
            } catch {
                Logger.shared.logVerbose("musickit", "Catalog search failed for \(track.title): \(error.localizedDescription)")
            }
        }
        if resolved.isEmpty {
            Logger.shared.logMinimal("musickit", "Nexus DJ: 0/\(rec.tracks.count) tracks resolved; skipping playlist create")
            return
        }
        Logger.shared.log("musickit", "Nexus DJ: resolved \(resolved.count)/\(rec.tracks.count) tracks against local catalog")

        // Find existing "Nexus DJ" playlist, or create one. Capture the
        // playlist's MusicItemID either way so we can build a deep link
        // back to the Apple Music app and pass it to the server's confirm
        // endpoint.
        do {
            let existingRequest = MusicLibraryRequest<Playlist>()
            let existing = try await existingRequest.response()
            let nexusDj = existing.items.first(where: { $0.name == "Nexus DJ" })

            let playlistId: String
            if let nexusDj {
                try await MusicLibrary.shared.edit(nexusDj, items: resolved)
                playlistId = nexusDj.id.rawValue
                Logger.shared.log("musickit", "Updated existing Nexus DJ playlist with \(resolved.count) tracks (id=\(playlistId.prefix(12))…)")
            } else {
                let created = try await MusicLibrary.shared.createPlaylist(
                    name: "Nexus DJ",
                    description: "Auto-generated by Nexus DJ. Updates ~30 min.",
                    items: resolved
                )
                playlistId = created.id.rawValue
                Logger.shared.log("musickit", "Created Nexus DJ playlist with \(resolved.count) tracks (id=\(playlistId.prefix(12))…)")
            }

            // Build the universal-link form. iOS handles
            // `music.apple.com/library/playlist/<id>` by routing taps from
            // any app (Discord, Safari, Messages) into the Music app.
            let appleMusicURL = "https://music.apple.com/library/playlist/\(playlistId)"
            try await APIClient.shared.confirmMusicRecommendation(id: rec.id, appleMusicURL: appleMusicURL)
        } catch {
            Logger.shared.logMinimal("musickit", "Nexus DJ playlist write failed: \(error.localizedDescription)")
        }
    }
}
